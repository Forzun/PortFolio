const COLORS = {
  faceOff: "#10101f",
  faceOn: "#fff200",
  glow: "#ffe600",
  glowOuter: "#ffb000",
};

const Runs = ({
  runs,
  fill,
}: {
  runs: [number, number, number][];
  fill?: string;
}) => (
  <>
    {runs.map(([x, y, w], i) => (
      <rect key={i} x={x} y={y} width={w + 0.02} height={1.02} fill={fill} />
    ))}
  </>
);

type Props = {
  size?: number | string;
  className?: string;
  style?: React.CSSProperties;
};

export default function PixelPumpkin({ size = 360, className, style }: Props) {
  const width = size;
  const height = typeof size === "number" ? (size * H) / W : size;

  return (
    <svg
      className={`pixel-pumpkin shrink-0 ${className ?? ""}`}
      width={width}
      height={height}
      style={{
        width,
        height,
        ...style,
      }}
      viewBox={`0 0 ${W} ${H}`}
      shapeRendering="crispEdges"
      xmlns="http://www.w3.org/2000/svg"
      role="img"
      aria-label="Pixel art jack-o'-lantern"
    >
      <style>{`
        .pixel-pumpkin { cursor: pointer; overflow: visible; }

        .pixel-pumpkin .face {
          fill: ${COLORS.faceOff};
          transition: fill 0.3s ease;
        }
        .pixel-pumpkin .glow,
        .pixel-pumpkin .warm {
          opacity: 0;
          transition: opacity 0.3s ease;
        }

        .pixel-pumpkin:hover .face { fill: ${COLORS.faceOn}; }
        .pixel-pumpkin:hover .glow {
          opacity: 1;
          animation: pumpkin-flicker 1.8s infinite ease-in-out;
        }
        .pixel-pumpkin:hover .warm { opacity: 0.22; }

        @keyframes pumpkin-flicker {
          0%, 100% { opacity: 1; }
          40%      { opacity: 0.8; }
          55%      { opacity: 0.95; }
          80%      { opacity: 0.85; }
        }

        @media (prefers-reduced-motion: reduce) {
          .pixel-pumpkin:hover .glow { animation: none; }
        }
      `}</style>

      <defs>
        <filter
          id="pumpkin-blur-tight"
          x="-50%"
          y="-50%"
          width="200%"
          height="200%"
        >
          <feGaussianBlur stdDeviation="0.9" />
        </filter>
        <filter
          id="pumpkin-blur-wide"
          x="-100%"
          y="-100%"
          width="300%"
          height="300%"
        >
          <feGaussianBlur stdDeviation="3" />
        </filter>
        <radialGradient id="pumpkin-warm" cx="50%" cy="58%" r="48%">
          <stop offset="0%" stopColor={COLORS.glow} stopOpacity="0.9" />
          <stop offset="100%" stopColor={COLORS.glow} stopOpacity="0" />
        </radialGradient>
      </defs>

      {/* pumpkin body */}
      {BODY.map((g) => (
        <g key={g.c} fill={g.c}>
          <Runs runs={g.r} />
        </g>
      ))}

      {/* warm light washing over the body on hover */}
      <ellipse
        className="warm"
        cx={W / 2}
        cy={H * 0.6}
        rx={W * 0.42}
        ry={H * 0.34}
        fill="url(#pumpkin-warm)"
      />

      {/* yellow glow around the face (fades in on hover) */}
      <g className="glow">
        <g filter="url(#pumpkin-blur-wide)">
          <Runs runs={FACE} fill={COLORS.glowOuter} />
        </g>
        <g filter="url(#pumpkin-blur-tight)">
          <Runs runs={FACE} fill={COLORS.glow} />
        </g>
      </g>

      {/* eyes / nose / mouth: black when idle, yellow on hover */}
      <g className="face">
        <Runs runs={FACE} />
      </g>
    </svg>
  );
}
